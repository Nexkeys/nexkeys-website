#!/usr/bin/env node
/**
 * WORK DETAIL EXTRACTOR — one-time migration tool.
 *
 * Pulls the 16 long-form project write-ups out of the legacy work.html and
 * emits lib/data/project-details.ts.
 *
 * WHY THIS EXISTS
 * The first pass of the rebuild generated `PROJECT_DETAILS` with
 * `description: ''` for every entry and never rendered it — so ~16 substantial
 * paragraphs of copy were silently dropped, in violation of plan N1 ("every
 * word of copy carries over verbatim"). Parsing the source guarantees fidelity
 * and can be re-run if the copy is revised.
 *
 * Matching is by URL, not by position: the card order in work.html and the
 * order in lib/data/projects.ts are not guaranteed to agree, and matching on
 * index would silently attach the wrong write-up to the wrong project.
 *
 * Run: node scripts/extract-work-details.mjs
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse } from 'node-html-parser';

const root = join(fileURLToPath(new URL('.', import.meta.url)), '..');
const legacy = join(root, '..', 'Nexkeys Website', 'work.html');

function decode(raw) {
  return raw
    .replace(/&nbsp;/g, ' ')
    .replace(/&amp;/g, '&')
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'")
    .replace(/&rsquo;/g, '’')
    .replace(/&lsquo;/g, '‘')
    .replace(/&ldquo;/g, '“')
    .replace(/&rdquo;/g, '”')
    .replace(/&mdash;/g, '—')
    .replace(/&ndash;/g, '–')
    .replace(/&hellip;/g, '…')
    .replace(/&#x[0-9A-Fa-f]+;/g, (m) => String.fromCodePoint(parseInt(m.slice(3, -1), 16)))
    .replace(/\s+/g, ' ')
    .trim();
}

const html = readFileSync(legacy, 'utf8');
const doc = parse(html);

/* The public project catalogue, so we can match by URL and reuse its ids. */
const projectsSrc = readFileSync(join(root, 'lib/data/projects.ts'), 'utf8');
const catalogue = [...projectsSrc.matchAll(/id:\s*'([^']+)',[\s\S]*?url:\s*'([^']+)'/g)].map(
  (m) => ({ id: m[1], url: m[2] })
);

const normaliseUrl = (u) => (u || '').trim().replace(/\/+$/, '').toLowerCase();
const byUrl = new Map(catalogue.map((c) => [normaliseUrl(c.url), c.id]));

const details = [];
const unmatched = [];

for (const article of doc.querySelectorAll('.project-item')) {
  const index = decode(article.querySelector('.proj-num')?.text ?? '');
  const name = decode(article.querySelector('.proj-name')?.text ?? '');
  const tags = article.querySelectorAll('.proj-tag').map((t) => decode(t.text));
  const label = decode(article.querySelector('.proj-fallback')?.text ?? '');

  const linkEl = article.querySelector('.proj-link');
  const url = linkEl?.getAttribute('href') ?? '';

  /* `<br><br>` is the paragraph separator in the source. Split on it BEFORE
     stripping tags, otherwise two paragraphs merge into one run-on block. */
  const descEl = article.querySelector('.proj-desc');
  const rawHtml = descEl?.innerHTML ?? '';
  const paragraphs = rawHtml
    .split(/(?:<br\s*\/?>\s*){2,}/i)
    .map((chunk) => decode(chunk.replace(/<[^>]+>/g, ' ')))
    .filter(Boolean);

  const id = byUrl.get(normaliseUrl(url));
  if (!id) {
    unmatched.push({ name, url });
    continue;
  }

  details.push({ id, index, name, tags, paragraphs, url, label });
}

const body = `// GENERATED by scripts/extract-work-details.mjs — do not edit by hand.
// Source: ../../../Nexkeys Website/work.html
// The long-form project write-ups, preserved verbatim (plan N1).
// Re-run the script if the source copy is revised.

import type { WorkDetail } from '@/lib/types';

export const WORK_DETAILS: WorkDetail[] = ${JSON.stringify(details, null, 2)};

export const WORK_DETAIL_BY_ID = Object.fromEntries(
  WORK_DETAILS.map((d) => [d.id, d])
) as Record<string, WorkDetail>;
`;

writeFileSync(join(root, 'lib/data/project-details.ts'), body, 'utf8');

const words = details
  .flatMap((d) => d.paragraphs)
  .join(' ')
  .split(/\s+/)
  .filter(Boolean).length;

console.log(`\n  ✓ Work details extracted\n`);
console.log(`      ${details.length} write-ups, ${words} words of copy`);
console.log(
  `      paragraphs per entry: ${details.map((d) => d.paragraphs.length).join(', ')}`
);
if (unmatched.length) {
  console.log(`\n  ! ${unmatched.length} article(s) had no matching project URL:`);
  for (const u of unmatched) console.log(`      ${u.name} — ${u.url}`);
}
console.log('');
